export function getExperienceProgress(rawExperience: number) {
  const experience = Math.max(0, Math.floor(rawExperience));
  let index = 0;

  for (let i = 1; i < EXPERIENCE_STAGES.length; i += 1) {
    if (EXPERIENCE_STAGES[i].experience > experience) break;
    index = i;
  }

  const current = EXPERIENCE_STAGES[index];
  const nextStage = EXPERIENCE_STAGES[index + 1];
  const nextLevel = EXPERIENCE_STAGES.find(
    (stage) => stage.level === current.level + 1 && stage.up === 0,
  );

  return {
    experience,
    level: current.level,
    up: current.up,
    currentStageExperience: current.experience,
    nextStage,
    nextLevel,
    toNextUp: nextStage ? Math.max(0, nextStage.experience - experience) : null,
    toNextLevel: nextLevel ? Math.max(0, nextLevel.experience - experience) : null,
    stageProgress: nextStage
      ? Math.min(
          100,
          Math.max(
            0,
            ((experience - current.experience) /
              (nextStage.experience - current.experience)) *
              100,
          ),
        )
      : 100,
  };
}
